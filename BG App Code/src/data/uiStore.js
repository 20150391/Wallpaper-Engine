let name = localStorage.getItem('sv-display-name') || '';
let query = '';
let promptOpen = !name;
const listeners = new Set();
const emit = () => listeners.forEach(cb => cb());
export const getUI = () => ({ name, query, promptOpen });
export const subscribeUI = (cb) => { listeners.add(cb); return () => listeners.delete(cb); };
export const setName = (n) => { name = n; localStorage.setItem('sv-display-name', n); emit(); };
export const setQuery = (q) => { query = q; emit(); };
export const openPrompt = () => { promptOpen = true; emit(); };
export const closePrompt = () => { promptOpen = false; emit(); };